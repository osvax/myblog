<?php

/**
 * Сгенерировать slug из произвольного текста: кириллица транслитерируется,
 * пробелы и прочие символы заменяются на тире, результат в нижнем регистре.
 *
 * Пример: slugify('Опыт и карьера') → 'opyt-i-karera'
 */
function slugify(string $value): string
{
    $translit = [
        'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'е' => 'e',
        'ё' => 'yo', 'ж' => 'zh', 'з' => 'z', 'и' => 'i', 'й' => 'y', 'к' => 'k',
        'л' => 'l', 'м' => 'm', 'н' => 'n', 'о' => 'o', 'п' => 'p', 'р' => 'r',
        'с' => 's', 'т' => 't', 'у' => 'u', 'ф' => 'f', 'х' => 'h', 'ц' => 'ts',
        'ч' => 'ch', 'ш' => 'sh', 'щ' => 'sch', 'ъ' => '', 'ы' => 'y', 'ь' => '',
        'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
    ];

    $value = mb_strtolower(trim($value));
    $value = strtr($value, $translit);
    $value = preg_replace('/[^a-z0-9]+/', '-', $value) ?? '';
    $value = preg_replace('/-+/', '-', $value) ?? '';

    return trim($value, '-');
}
