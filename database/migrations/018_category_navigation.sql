CREATE TABLE IF NOT EXISTS {CATEGORY_NAVIGATION_TABLE} (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    category_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(160) NOT NULL,
    url VARCHAR(255) NOT NULL,
    icon VARCHAR(80) NOT NULL DEFAULT '',
    display_order INT NOT NULL DEFAULT 0,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_category_navigation_category (category_id, display_order),
    CONSTRAINT fk_category_navigation_category FOREIGN KEY (category_id) REFERENCES {CATEGORIES_TABLE}(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
